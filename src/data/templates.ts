export function applyTemplateDefaults(
  current: PaperSettings,
  templateId: PaperTypeId,
): PaperSettings {
  const tpl = getTemplateSpec(templateId);
  return {
    ...current,
    paperType: templateId,
    lineSpacingMm: tpl.defaultSpacingMm,
    lineWidthPx: tpl.defaultLineWidthPx,
    orientation: tpl.defaultOrientation ?? "portrait",
    ...(tpl.defaultLineColor ? { lineColor: tpl.defaultLineColor } : {}),
    ...(tpl.defaultAccentColor ? { accentColor: tpl.defaultAccentColor } : {}),
    ...(tpl.defaultShowLeftMarginRule !== undefined
      ? { showLeftMarginRule: tpl.defaultShowLeftMarginRule }
      : {}),
    ...(tpl.defaultSlantAngleDeg !== undefined
      ? { slantAngleDeg: tpl.defaultSlantAngleDeg }
      : {}),
  };
}
